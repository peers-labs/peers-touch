export type StringKey = keyof (typeof STRINGS)['zh-CN'];

export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

export function makeTranslate(locale: Locale): Translate {
  return (key, vars) => {
    const table = STRINGS[locale] ?? STRINGS['zh-CN'];
    const fallback = STRINGS['zh-CN'][key] ?? key;
    const template = (table as Record<string, string>)[key] ?? fallback;
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
  };
}

export function useT(): { t: Translate; locale: Locale } {
  const prefs = usePrefs();
  return { t: makeTranslate(prefs.locale), locale: prefs.locale };
}
