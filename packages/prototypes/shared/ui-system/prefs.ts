/**
 * Shared local preferences for the north-star prototype.
 *
 * The prototype has no real settings transport; preferences persist in
 * localStorage and broadcast a window event so unrelated surfaces (settings
 * page, chat, moments) re-render together. This module owns:
 *  - interface locale (zh-CN / en)
 *  - message layout (sides: own-right/peer-left | left: unified left)
 *  - notification preferences (mentions / invites / requests / …)
 *
 * i18n is a keyed dictionary (zh/en). Components call useT() and render
 * t('key') instead of inline literals; seeded content (messages, names,
 * demo records) stays as authored and is not translated.
 */
import { useEffect, useState } from 'react';

export type Locale = 'zh-CN' | 'en';
export type MessageLayout = 'sides' | 'left';

export type NotificationPrefs = {
  mentions: boolean;
  invites: boolean;
  friendRequests: boolean;
  reactions: boolean;
  network: boolean;
  inApp: boolean;
  sound: boolean;
};

export type Prefs = {
  locale: Locale;
  messageLayout: MessageLayout;
  notifications: NotificationPrefs;
};

const STORAGE_KEY = 'north-star.prefs.v1';
const EVENT = 'north-star-prefs-change';

export const DEFAULT_PREFS: Prefs = {
  locale: 'zh-CN',
  messageLayout: 'sides',
  notifications: {
    mentions: true,
    invites: true,
    friendRequests: true,
    reactions: false,
    network: true,
    inApp: true,
    sound: false,
  },
};

function read(): Prefs {
  if (typeof localStorage === 'undefined') return DEFAULT_PREFS;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return DEFAULT_PREFS;
    const parsed = JSON.parse(raw) as Partial<Prefs>;
    return {
      ...DEFAULT_PREFS,
      ...parsed,
      notifications: { ...DEFAULT_PREFS.notifications, ...(parsed.notifications ?? {}) },
    };
  } catch {
    return DEFAULT_PREFS;
  }
}

let cache: Prefs = typeof window !== 'undefined' ? read() : DEFAULT_PREFS;

export function getPrefs(): Prefs {
  return cache;
}

export function setPrefs(patch: Partial<Prefs>) {
  cache = { ...cache, ...patch };
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(cache));
  }
  window.dispatchEvent(new CustomEvent(EVENT));
}

export function patchNotifications(patch: Partial<NotificationPrefs>) {
  setPrefs({ notifications: { ...cache.notifications, ...patch } });
}

export function usePrefs(): Prefs {
  const [prefs, setLocal] = useState<Prefs>(cache);
  useEffect(() => {
    const sync = () => setLocal({ ...getPrefs() });
    window.addEventListener(EVENT, sync);
    return () => window.removeEventListener(EVENT, sync);
  }, []);
  return prefs;
}

/** BCP-47 tag for Intl / toLocale* helpers. */
export function locTag(locale: Locale): string {
  return locale === 'en' ? 'en-US' : 'zh-CN';
}

