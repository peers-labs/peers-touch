#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FriendRequestTransportFailure {
    Deadline,
    ResponseDecode,
    Transport,
}

impl FriendRequestTransportFailure {
    fn command_error(self) -> MobileDurableCommandErrorCode {
        match self {
            Self::Deadline => MobileDurableCommandErrorCode::Deadline,
            Self::ResponseDecode => MobileDurableCommandErrorCode::ResponseDecode,
            Self::Transport => MobileDurableCommandErrorCode::Transport,
        }
    }
}

impl std::fmt::Display for FriendRequestTransportFailure {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(match self {
            Self::Deadline => "Friend Request transport deadline exceeded",
            Self::ResponseDecode => "Friend Request response is invalid",
            Self::Transport => "Friend Request transport is unavailable",
        })
    }
}

pub trait FriendRequestResolverTransport {
    fn dispatch(
        &self,
        exact_payload_bytes: &[u8],
    ) -> Result<Vec<u8>, FriendRequestTransportFailure>;

    fn lookup(
        &self,
        command_id: &str,
        payload_sha256: &[u8],
    ) -> Result<Vec<u8>, FriendRequestTransportFailure>;
}

#[derive(Debug, Clone, PartialEq)]
pub struct PreparedFriendRequestAdmission {
    pub command_id: String,
    pub ordering_key: String,
    pub payload_sha256: Vec<u8>,
    pub exact_payload_bytes: Vec<u8>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct FriendRequestResolution {
    pub command_id: String,
    pub payload_sha256: Vec<u8>,
    pub state: MobileDurableCommandState,
    pub dispatch_response_bytes: Option<Vec<u8>>,
    pub projection_checkpoint: Option<ProjectionCheckpoint>,
}

pub struct FriendRequestResolver;

impl FriendRequestResolver {
    pub fn admit(
        ledger: &CommandLedger,
        scope: &ExactScope,
        runtime_generation: u64,
        prepared: PreparedFriendRequestAdmission,
    ) -> LedgerResult<AdmissionOutcome> {
        let command = FriendRequestCommand::decode(prepared.exact_payload_bytes.as_slice())
            .map_err(|error| {
                LedgerError::for_command(
                    LedgerErrorCode::Serialization,
                    "decode prepared Friend Request",
                    &prepared.command_id,
                    error.to_string(),
                )
            })?;
        if command.encode_to_vec() != prepared.exact_payload_bytes {
            return Err(LedgerError::for_command(
                LedgerErrorCode::InvalidEnvelope,
                "admit prepared Friend Request",
                &prepared.command_id,
                "prepared payload bytes are not canonical",
            ));
        }
        let body = command.body.as_ref().ok_or_else(|| {
            LedgerError::for_command(
                LedgerErrorCode::InvalidEnvelope,
                "admit prepared Friend Request",
                &prepared.command_id,
                "generated Friend Request body is required",
            )
        })?;
        if body.command_id != prepared.command_id
            || Sha256::digest(&prepared.exact_payload_bytes).as_slice()
                != prepared.payload_sha256.as_slice()
        {
            return Err(LedgerError::for_command(
                LedgerErrorCode::CommandConflict,
                "admit prepared Friend Request",
                &prepared.command_id,
                "prepared command ID or payload hash differs from exact generated bytes",
            ));
        }
        let created_at = body.created_at.clone().ok_or_else(|| {
            LedgerError::for_command(
                LedgerErrorCode::InvalidEnvelope,
                "admit prepared Friend Request",
                &prepared.command_id,
                "generated Friend Request created_at is required",
            )
        })?;
        let expires_at = body.expires_at.clone().ok_or_else(|| {
            LedgerError::for_command(
                LedgerErrorCode::InvalidEnvelope,
                "admit prepared Friend Request",
                &prepared.command_id,
                "generated Friend Request expires_at is required",
            )
        })?;
        let envelope = MobileDurableCommandEnvelopeV2 {
            schema_revision: super::RELIABILITY_SCHEMA_REVISION,
            command_id: prepared.command_id,
            station_peer_id: scope.station_peer_id().to_string(),
            actor_ptid: scope.actor_ptid().to_string(),
            origin_generation: runtime_generation,
            ordering_key: prepared.ordering_key,
            payload_sha256: prepared.payload_sha256,
            created_at: Some(created_at.clone()),
            updated_at: Some(created_at),
            expires_at: Some(expires_at),
            attempt_count: 0,
            state: MobileDurableCommandState::Queued as i32,
            typed_last_error: MobileDurableCommandErrorCode::Unspecified as i32,
            dispatch_started_at: None,
            next_attempt_at: None,
            payload: Some(mobile_durable_command_envelope_v2::Payload::FriendRequest(
                command,
            )),
        };
        ledger.admit_generated_envelope(&envelope.encode_to_vec())
    }

    pub fn resolve_next<T: FriendRequestResolverTransport>(
        ledger: &CommandLedger,
        transport: &T,
        runtime_generation: u64,
        now_ms: i64,
        retry_entropy: u64,
    ) -> LedgerResult<Option<FriendRequestResolution>> {
        let Some(lease) = ledger.next_for_dispatch_kind(
            runtime_generation,
            now_ms,
            Some(CommandPayloadKind::FriendRequest),
        )?
        else {
            return Ok(None);
        };
        let command_id = lease.envelope.command_id.clone();
        let payload_sha256 = lease.envelope.payload_sha256.clone();
        match lease.envelope.payload.as_ref() {
            Some(mobile_durable_command_envelope_v2::Payload::FriendRequest(_)) => {}
            _ => {
                return Err(LedgerError::for_command(
                    LedgerErrorCode::InvalidEnvelope,
                    "resolve generated command",
                    &command_id,
                    "generated command payload is missing",
                ));
            }
        }

        ledger.mark_submitting(&command_id, runtime_generation, now_ms)?;
        let dispatch_result = transport.dispatch(&lease.exact_payload_bytes);
        let dispatch_response_bytes = match dispatch_result {
            Ok(response) => Some(response),
            Err(failure) => {
                ledger.mark_unknown(
                    &command_id,
                    runtime_generation,
                    failure.command_error(),
                    now_ms,
                )?;
                ledger.begin_reconciliation(
                    &command_id,
                    MobileDurableCommandState::UnknownOutcome,
                    runtime_generation,
                    now_ms,
                )?;
                None
            }
        };

        let lookup_bytes = match transport.lookup(&command_id, &payload_sha256) {
            Ok(lookup) => lookup,
            Err(failure) => {
                if dispatch_response_bytes.is_some() {
                    ledger.mark_unknown(
                        &command_id,
                        runtime_generation,
                        failure.command_error(),
                        now_ms,
                    )?;
                    ledger.begin_reconciliation(
                        &command_id,
                        MobileDurableCommandState::UnknownOutcome,
                        runtime_generation,
                        now_ms,
                    )?;
                }
                let envelope = ledger.mark_reconciliation_unresolved(
                    &command_id,
                    runtime_generation,
                    failure.command_error(),
                    now_ms,
                )?;
                return Ok(Some(FriendRequestResolution {
                    command_id,
                    payload_sha256,
                    state: state_of(&envelope)?,
                    dispatch_response_bytes,
                    projection_checkpoint: None,
                }));
            }
        };
        let transition = ledger.transition_from_authoritative_lookup(
            &command_id,
            &lookup_bytes,
            runtime_generation,
            now_ms,
            command_retry_entropy(retry_entropy, &command_id, &payload_sha256),
        )?;
        let state = state_of(&transition.envelope)?;
        let projection_checkpoint = if matches!(
            state,
            MobileDurableCommandState::AcceptedPending | MobileDurableCommandState::Committed
        ) {
            Some(ledger.persist_projection_checkpoint_and_remove(
                &command_id,
                &lookup_bytes,
                runtime_generation,
                now_ms,
            )?)
        } else {
            None
        };
        Ok(Some(FriendRequestResolution {
            command_id,
            payload_sha256,
            state,
            dispatch_response_bytes,
            projection_checkpoint,
        }))
    }

    pub fn reconcile_existing<T: FriendRequestResolverTransport + Sync>(
        ledger: &CommandLedger,
        transport: &T,
        runtime_generation: u64,
        now_ms: i64,
        retry_entropy: u64,
    ) -> LedgerResult<Vec<FriendRequestResolution>> {
        let mut resolutions = Vec::new();
        let existing = ledger.list()?;
        for envelope in existing {
            if !matches!(
                envelope.payload.as_ref(),
                Some(mobile_durable_command_envelope_v2::Payload::FriendRequest(
                    _
                ))
            ) {
                continue;
            }
            let state = state_of(&envelope)?;
            match state {
                MobileDurableCommandState::UnknownOutcome
                | MobileDurableCommandState::Unresolved => {
                    ledger.begin_reconciliation(
                        &envelope.command_id,
                        state,
                        runtime_generation,
                        now_ms,
                    )?;
                    resolutions.push(resolve_lookup_only(
                        ledger,
                        transport,
                        envelope.command_id,
                        envelope.payload_sha256,
                        runtime_generation,
                        now_ms,
                        retry_entropy,
                    )?);
                }
                MobileDurableCommandState::Reconciling => {
                    resolutions.push(resolve_lookup_only(
                        ledger,
                        transport,
                        envelope.command_id,
                        envelope.payload_sha256,
                        runtime_generation,
                        now_ms,
                        retry_entropy,
                    )?);
                }
                MobileDurableCommandState::AcceptedPending
                | MobileDurableCommandState::Committed => {
                    resolutions.push(checkpoint_existing(
                        ledger,
                        transport,
                        envelope.command_id,
                        envelope.payload_sha256,
                        runtime_generation,
                        now_ms,
                        retry_entropy,
                    )?);
                }
                _ => {}
            }
        }
        loop {
            let wave = std::thread::scope(|scope| {
                let handles = (0..MAX_ACTIVE_ORDERING_KEYS)
                    .map(|_| {
                        scope.spawn(|| {
                            Self::resolve_next(
                                ledger,
                                transport,
                                runtime_generation,
                                now_ms,
                                retry_entropy,
                            )
                        })
                    })
                    .collect::<Vec<_>>();
                handles
                    .into_iter()
                    .map(|handle| {
                        handle.join().map_err(|_| {
                            LedgerError::new(
                                LedgerErrorCode::Storage,
                                "dispatch Friend Request reconciliation wave",
                                "resolver worker panicked",
                            )
                        })?
                    })
                    .collect::<LedgerResult<Vec<_>>>()
            })?;
            let mut dispatched = false;
            for resolution in wave.into_iter().flatten() {
                dispatched = true;
                resolutions.push(resolution);
            }
            if !dispatched {
                break;
            }
        }
        Ok(resolutions)
    }
}

fn resolve_lookup_only<T: FriendRequestResolverTransport>(
    ledger: &CommandLedger,
    transport: &T,
    command_id: String,
    payload_sha256: Vec<u8>,
    runtime_generation: u64,
    now_ms: i64,
    retry_entropy: u64,
) -> LedgerResult<FriendRequestResolution> {
    let lookup_bytes = match transport.lookup(&command_id, &payload_sha256) {
        Ok(lookup) => lookup,
        Err(failure) => {
            let unresolved = ledger.mark_reconciliation_unresolved(
                &command_id,
                runtime_generation,
                failure.command_error(),
                now_ms,
            )?;
            return Ok(FriendRequestResolution {
                command_id,
                payload_sha256,
                state: state_of(&unresolved)?,
                dispatch_response_bytes: None,
                projection_checkpoint: None,
            });
        }
    };
    let transition = ledger.transition_from_authoritative_lookup(
        &command_id,
        &lookup_bytes,
        runtime_generation,
        now_ms,
        command_retry_entropy(retry_entropy, &command_id, &payload_sha256),
    )?;
    let state = state_of(&transition.envelope)?;
    let projection_checkpoint = if matches!(
        state,
        MobileDurableCommandState::AcceptedPending | MobileDurableCommandState::Committed
    ) {
        Some(ledger.persist_projection_checkpoint_and_remove(
            &command_id,
            &lookup_bytes,
            runtime_generation,
            now_ms,
        )?)
    } else {
        None
    };
    Ok(FriendRequestResolution {
        command_id,
        payload_sha256,
        state,
        dispatch_response_bytes: None,
        projection_checkpoint,
    })
}

fn checkpoint_existing<T: FriendRequestResolverTransport>(
    ledger: &CommandLedger,
    transport: &T,
    command_id: String,
    payload_sha256: Vec<u8>,
    runtime_generation: u64,
    now_ms: i64,
    retry_entropy: u64,
) -> LedgerResult<FriendRequestResolution> {
    let current = ledger.get(&command_id)?.ok_or_else(|| {
        LedgerError::for_command(
            LedgerErrorCode::CommandNotFound,
            "refresh authoritative checkpoint",
            &command_id,
            "command disappeared before checkpoint refresh",
        )
    })?;
    let current_state = state_of(&current)?;
    let lookup_bytes = match transport.lookup(&command_id, &payload_sha256) {
        Ok(lookup) => lookup,
        Err(_) => {
            return Ok(FriendRequestResolution {
                command_id,
                payload_sha256,
                state: current_state,
                dispatch_response_bytes: None,
                projection_checkpoint: None,
            });
        }
    };
    let lookup = LookupFriendRequestCommandResultResponse::decode(lookup_bytes.as_slice())
        .map_err(|error| {
            LedgerError::for_command(
                LedgerErrorCode::Serialization,
                "decode authoritative checkpoint refresh",
                &command_id,
                error.to_string(),
            )
        })?;
    if lookup.encode_to_vec() != lookup_bytes {
        return Err(LedgerError::for_command(
            LedgerErrorCode::InvalidEnvelope,
            "decode authoritative checkpoint refresh",
            &command_id,
            "lookup bytes are not canonical",
        ));
    }
    let lookup_state = FriendRequestCommandLookupState::try_from(lookup.state).map_err(|_| {
        LedgerError::for_command(
            LedgerErrorCode::InvalidEnvelope,
            "decode authoritative checkpoint refresh",
            &command_id,
            "lookup state is unknown",
        )
    })?;
    let resolved_state = if current_state == MobileDurableCommandState::AcceptedPending
        && lookup_state == FriendRequestCommandLookupState::TerminalResult
    {
        state_of(
            &ledger
                .transition_from_authoritative_lookup(
                    &command_id,
                    &lookup_bytes,
                    runtime_generation,
                    now_ms,
                    command_retry_entropy(retry_entropy, &command_id, &payload_sha256),
                )?
                .envelope,
        )?
    } else {
        current_state
    };
    let checkpoint = if matches!(
        resolved_state,
        MobileDurableCommandState::AcceptedPending | MobileDurableCommandState::Committed
    ) {
        Some(ledger.persist_projection_checkpoint_and_remove(
            &command_id,
            &lookup_bytes,
            runtime_generation,
            now_ms,
        )?)
    } else {
        None
    };
    Ok(FriendRequestResolution {
        command_id,
        payload_sha256,
        state: resolved_state,
        dispatch_response_bytes: None,
        projection_checkpoint: checkpoint,
    })
}

fn command_retry_entropy(seed: u64, command_id: &str, payload_sha256: &[u8]) -> u64 {
    let mut hasher = Sha256::new();
    hasher.update(b"peers-touch/mobile/friend-request-retry-jitter/v1");
    hasher.update(seed.to_be_bytes());
    hasher.update(command_id.as_bytes());
    hasher.update(payload_sha256);
    let digest = hasher.finalize();
    u64::from_be_bytes(
        digest[..8]
            .try_into()
            .expect("SHA-256 always contains at least eight bytes"),
    )
}

