#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RelationshipTransportFailure {
    Deadline,
    ResponseDecode,
    Transport,
}

impl RelationshipTransportFailure {
    fn command_error(self) -> MobileDurableCommandErrorCode {
        match self {
            Self::Deadline => MobileDurableCommandErrorCode::Deadline,
            Self::ResponseDecode => MobileDurableCommandErrorCode::ResponseDecode,
            Self::Transport => MobileDurableCommandErrorCode::Transport,
        }
    }
}

impl std::fmt::Display for RelationshipTransportFailure {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(match self {
            Self::Deadline => "Social relationship transport deadline exceeded",
            Self::ResponseDecode => "Social relationship response is invalid",
            Self::Transport => "Social relationship transport is unavailable",
        })
    }
}

pub trait RelationshipResolverTransport {
    fn dispatch(&self, exact_payload_bytes: &[u8])
        -> Result<Vec<u8>, RelationshipTransportFailure>;

    fn lookup(
        &self,
        command_id: &str,
        payload_sha256: &[u8],
    ) -> Result<Vec<u8>, RelationshipTransportFailure>;
}

#[derive(Debug, Clone, PartialEq)]
pub struct PreparedRelationshipAdmission {
    pub command_id: String,
    pub ordering_key: String,
    pub payload_sha256: Vec<u8>,
    pub exact_payload_bytes: Vec<u8>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct RelationshipResolution {
    pub command_id: String,
    pub payload_sha256: Vec<u8>,
    pub state: MobileDurableCommandState,
    pub dispatch_response_bytes: Option<Vec<u8>>,
    pub projection_checkpoint: Option<ProjectionCheckpoint>,
}

pub struct RelationshipResolver;

impl RelationshipResolver {
    pub fn admit(
        ledger: &CommandLedger,
        scope: &ExactScope,
        runtime_generation: u64,
        prepared: PreparedRelationshipAdmission,
    ) -> LedgerResult<AdmissionOutcome> {
        let command = SocialRelationshipCommand::decode(prepared.exact_payload_bytes.as_slice())
            .map_err(|error| {
                LedgerError::for_command(
                    LedgerErrorCode::Serialization,
                    "decode prepared Social relationship command",
                    &prepared.command_id,
                    error.to_string(),
                )
            })?;
        if command.encode_to_vec() != prepared.exact_payload_bytes {
            return Err(LedgerError::for_command(
                LedgerErrorCode::InvalidEnvelope,
                "admit prepared Social relationship command",
                &prepared.command_id,
                "prepared payload bytes are not canonical",
            ));
        }
        let body = command.body.as_ref().ok_or_else(|| {
            LedgerError::for_command(
                LedgerErrorCode::InvalidEnvelope,
                "admit prepared Social relationship command",
                &prepared.command_id,
                "generated Social relationship body is required",
            )
        })?;
        if body.command_id != prepared.command_id
            || Sha256::digest(&prepared.exact_payload_bytes).as_slice()
                != prepared.payload_sha256.as_slice()
        {
            return Err(LedgerError::for_command(
                LedgerErrorCode::CommandConflict,
                "admit prepared Social relationship command",
                &prepared.command_id,
                "prepared command ID or payload hash differs from exact generated bytes",
            ));
        }
        let created_at = body.created_at.clone().ok_or_else(|| {
            LedgerError::for_command(
                LedgerErrorCode::InvalidEnvelope,
                "admit prepared Social relationship command",
                &prepared.command_id,
                "generated Social relationship created_at is required",
            )
        })?;
        let expires_at = body.expires_at.clone().ok_or_else(|| {
            LedgerError::for_command(
                LedgerErrorCode::InvalidEnvelope,
                "admit prepared Social relationship command",
                &prepared.command_id,
                "generated Social relationship expires_at is required",
            )
        })?;
        let envelope = MobileDurableCommandEnvelopeV2 {
            schema_revision: super::RELIABILITY_SCHEMA_REVISION,
            command_id: prepared.command_id,
            station_peer_id: scope.station_peer_id().to_string(),
            actor_ptid: scope.actor_ptid().to_string(),
            origin_generation: runtime_generation,
            ordering_key: prepared.ordering_key,
            payload_sha256: prepared.payload_sha256,
            created_at: Some(created_at.clone()),
            updated_at: Some(created_at),
            expires_at: Some(expires_at),
            attempt_count: 0,
            state: MobileDurableCommandState::Queued as i32,
            typed_last_error: MobileDurableCommandErrorCode::Unspecified as i32,
            dispatch_started_at: None,
            next_attempt_at: None,
            payload: Some(mobile_durable_command_envelope_v2::Payload::SocialRelationship(command)),
        };
        ledger.admit_generated_envelope(&envelope.encode_to_vec())
    }

    pub fn resolve_next<T: RelationshipResolverTransport>(
        ledger: &CommandLedger,
        transport: &T,
        runtime_generation: u64,
        now_ms: i64,
        retry_entropy: u64,
    ) -> LedgerResult<Option<RelationshipResolution>> {
        let Some(lease) = ledger.next_for_dispatch_kind(
            runtime_generation,
            now_ms,
            Some(CommandPayloadKind::SocialRelationship),
        )?
        else {
            return Ok(None);
        };
        let command_id = lease.envelope.command_id.clone();
        let payload_sha256 = lease.envelope.payload_sha256.clone();
        if !matches!(
            lease.envelope.payload.as_ref(),
            Some(mobile_durable_command_envelope_v2::Payload::SocialRelationship(_))
        ) {
            return Err(LedgerError::for_command(
                LedgerErrorCode::InvalidEnvelope,
                "resolve Social relationship command",
                &command_id,
                "generated relationship payload is missing",
            ));
        }

        ledger.mark_submitting(&command_id, runtime_generation, now_ms)?;
        let dispatch_response_bytes = match transport.dispatch(&lease.exact_payload_bytes) {
            Ok(response) => Some(response),
            Err(failure) => {
                ledger.mark_unknown(
                    &command_id,
                    runtime_generation,
                    failure.command_error(),
                    now_ms,
                )?;
                ledger.begin_reconciliation(
                    &command_id,
                    MobileDurableCommandState::UnknownOutcome,
                    runtime_generation,
                    now_ms,
                )?;
                None
            }
        };

        let lookup_bytes = match transport.lookup(&command_id, &payload_sha256) {
            Ok(lookup) => lookup,
            Err(failure) => {
                if dispatch_response_bytes.is_some() {
                    ledger.mark_unknown(
                        &command_id,
                        runtime_generation,
                        failure.command_error(),
                        now_ms,
                    )?;
                    ledger.begin_reconciliation(
                        &command_id,
                        MobileDurableCommandState::UnknownOutcome,
                        runtime_generation,
                        now_ms,
                    )?;
                }
                let envelope = ledger.mark_reconciliation_unresolved(
                    &command_id,
                    runtime_generation,
                    failure.command_error(),
                    now_ms,
                )?;
                return Ok(Some(RelationshipResolution {
                    command_id,
                    payload_sha256,
                    state: state_of(&envelope)?,
                    dispatch_response_bytes,
                    projection_checkpoint: None,
                }));
            }
        };
        relationship_resolution_from_lookup(
            ledger,
            command_id,
            payload_sha256,
            dispatch_response_bytes,
            lookup_bytes,
            runtime_generation,
            now_ms,
            retry_entropy,
        )
        .map(Some)
    }

    pub fn reconcile_existing<T: RelationshipResolverTransport + Sync>(
        ledger: &CommandLedger,
        transport: &T,
        runtime_generation: u64,
        now_ms: i64,
        retry_entropy: u64,
    ) -> LedgerResult<Vec<RelationshipResolution>> {
        let mut resolutions = Vec::new();
        for envelope in ledger.list()? {
            if !matches!(
                envelope.payload.as_ref(),
                Some(mobile_durable_command_envelope_v2::Payload::SocialRelationship(_))
            ) {
                continue;
            }
            let state = state_of(&envelope)?;
            match state {
                MobileDurableCommandState::UnknownOutcome
                | MobileDurableCommandState::Unresolved => {
                    ledger.begin_reconciliation(
                        &envelope.command_id,
                        state,
                        runtime_generation,
                        now_ms,
                    )?;
                    resolutions.push(resolve_lookup_only(
                        ledger,
                        transport,
                        envelope.command_id,
                        envelope.payload_sha256,
                        runtime_generation,
                        now_ms,
                        retry_entropy,
                    )?);
                }
                MobileDurableCommandState::Reconciling => {
                    resolutions.push(resolve_lookup_only(
                        ledger,
                        transport,
                        envelope.command_id,
                        envelope.payload_sha256,
                        runtime_generation,
                        now_ms,
                        retry_entropy,
                    )?);
                }
                MobileDurableCommandState::AcceptedPending
                | MobileDurableCommandState::Committed => {
                    resolutions.push(checkpoint_existing(
                        ledger,
                        transport,
                        envelope.command_id,
                        envelope.payload_sha256,
                        runtime_generation,
                        now_ms,
                        retry_entropy,
                    )?);
                }
                _ => {}
            }
        }
        loop {
            let wave = std::thread::scope(|scope| {
                let handles = (0..MAX_ACTIVE_ORDERING_KEYS)
                    .map(|_| {
                        scope.spawn(|| {
                            Self::resolve_next(
                                ledger,
                                transport,
                                runtime_generation,
                                now_ms,
                                retry_entropy,
                            )
                        })
                    })
                    .collect::<Vec<_>>();
                handles
                    .into_iter()
                    .map(|handle| {
                        handle.join().map_err(|_| {
                            LedgerError::new(
                                LedgerErrorCode::Storage,
                                "dispatch Social relationship reconciliation wave",
                                "resolver worker panicked",
                            )
                        })?
                    })
                    .collect::<LedgerResult<Vec<_>>>()
            })?;
            let mut dispatched = false;
            for resolution in wave.into_iter().flatten() {
                dispatched = true;
                resolutions.push(resolution);
            }
            if !dispatched {
                break;
            }
        }
        Ok(resolutions)
    }
}

fn resolve_lookup_only<T: RelationshipResolverTransport>(
    ledger: &CommandLedger,
    transport: &T,
    command_id: String,
    payload_sha256: Vec<u8>,
    runtime_generation: u64,
    now_ms: i64,
    retry_entropy: u64,
) -> LedgerResult<RelationshipResolution> {
    let lookup_bytes = match transport.lookup(&command_id, &payload_sha256) {
        Ok(lookup) => lookup,
        Err(failure) => {
            let unresolved = ledger.mark_reconciliation_unresolved(
                &command_id,
                runtime_generation,
                failure.command_error(),
                now_ms,
            )?;
            return Ok(RelationshipResolution {
                command_id,
                payload_sha256,
                state: state_of(&unresolved)?,
                dispatch_response_bytes: None,
                projection_checkpoint: None,
            });
        }
    };
    relationship_resolution_from_lookup(
        ledger,
        command_id,
        payload_sha256,
        None,
        lookup_bytes,
        runtime_generation,
        now_ms,
        retry_entropy,
    )
}

#[allow(clippy::too_many_arguments)]
fn relationship_resolution_from_lookup(
    ledger: &CommandLedger,
    command_id: String,
    payload_sha256: Vec<u8>,
    dispatch_response_bytes: Option<Vec<u8>>,
    lookup_bytes: Vec<u8>,
    runtime_generation: u64,
    now_ms: i64,
    retry_entropy: u64,
) -> LedgerResult<RelationshipResolution> {
    let transition = ledger.transition_from_authoritative_lookup(
        &command_id,
        &lookup_bytes,
        runtime_generation,
        now_ms,
        command_retry_entropy(retry_entropy, &command_id, &payload_sha256),
    )?;
    let state = state_of(&transition.envelope)?;
    let projection_checkpoint = if matches!(
        state,
        MobileDurableCommandState::AcceptedPending | MobileDurableCommandState::Committed
    ) {
        Some(ledger.persist_projection_checkpoint_and_remove(
            &command_id,
            &lookup_bytes,
            runtime_generation,
            now_ms,
        )?)
    } else {
        None
    };
    Ok(RelationshipResolution {
        command_id,
        payload_sha256,
        state,
        dispatch_response_bytes,
        projection_checkpoint,
    })
}

fn checkpoint_existing<T: RelationshipResolverTransport>(
    ledger: &CommandLedger,
    transport: &T,
    command_id: String,
    payload_sha256: Vec<u8>,
    runtime_generation: u64,
    now_ms: i64,
    retry_entropy: u64,
) -> LedgerResult<RelationshipResolution> {
    let current = ledger.get(&command_id)?.ok_or_else(|| {
        LedgerError::for_command(
            LedgerErrorCode::CommandNotFound,
            "refresh Social relationship checkpoint",
            &command_id,
            "command disappeared before checkpoint refresh",
        )
    })?;
    let current_state = state_of(&current)?;
    let lookup_bytes = match transport.lookup(&command_id, &payload_sha256) {
        Ok(lookup) => lookup,
        Err(_) => {
            return Ok(RelationshipResolution {
                command_id,
                payload_sha256,
                state: current_state,
                dispatch_response_bytes: None,
                projection_checkpoint: None,
            });
        }
    };
    let lookup = LookupSocialRelationshipCommandResultResponse::decode(lookup_bytes.as_slice())
        .map_err(|error| {
            LedgerError::for_command(
                LedgerErrorCode::Serialization,
                "decode Social relationship checkpoint refresh",
                &command_id,
                error.to_string(),
            )
        })?;
    if lookup.encode_to_vec() != lookup_bytes {
        return Err(LedgerError::for_command(
            LedgerErrorCode::InvalidEnvelope,
            "decode Social relationship checkpoint refresh",
            &command_id,
            "lookup bytes are not canonical",
        ));
    }
    let lookup_state =
        SocialRelationshipCommandLookupState::try_from(lookup.state).map_err(|_| {
            LedgerError::for_command(
                LedgerErrorCode::InvalidEnvelope,
                "decode Social relationship checkpoint refresh",
                &command_id,
                "lookup state is unknown",
            )
        })?;
    let resolved_state = if current_state == MobileDurableCommandState::AcceptedPending
        && lookup_state == SocialRelationshipCommandLookupState::TerminalResult
    {
        state_of(
            &ledger
                .transition_from_authoritative_lookup(
                    &command_id,
                    &lookup_bytes,
                    runtime_generation,
                    now_ms,
                    command_retry_entropy(retry_entropy, &command_id, &payload_sha256),
                )?
                .envelope,
        )?
    } else {
        current_state
    };
    let checkpoint = if matches!(
        resolved_state,
        MobileDurableCommandState::AcceptedPending | MobileDurableCommandState::Committed
    ) {
        Some(ledger.persist_projection_checkpoint_and_remove(
            &command_id,
            &lookup_bytes,
            runtime_generation,
            now_ms,
        )?)
    } else {
        None
    };
    Ok(RelationshipResolution {
        command_id,
        payload_sha256,
        state: resolved_state,
        dispatch_response_bytes: None,
        projection_checkpoint: checkpoint,
    })
}

fn command_retry_entropy(seed: u64, command_id: &str, payload_sha256: &[u8]) -> u64 {
    let mut hasher = Sha256::new();
    hasher.update(b"peers-touch/mobile/social-relationship-retry-jitter/v1");
    hasher.update(seed.to_be_bytes());
    hasher.update(command_id.as_bytes());
    hasher.update(payload_sha256);
    let digest = hasher.finalize();
    u64::from_be_bytes(
        digest[..8]
            .try_into()
            .expect("SHA-256 always contains at least eight bytes"),
    )
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::{Path, PathBuf};

    use rand::RngCore;

    use super::*;
    use crate::runtime::command_ledger::{
        CommandScope, LedgerActivation, LedgerPaths, ScopeKeyMetadata, TrustedCommandKey,
    };
    use crate::runtime::reliability_proto::peers_touch::model::actor::v1::{
        ActorDeviceRef, ActorKind, ActorRef,
    };
    use crate::runtime::reliability_proto::peers_touch::model::social::v1::{
        SocialRelationshipAction, SocialRelationshipCommandBody,
        SocialRelationshipCommandLookupState, SocialRelationshipCommandResult,
        SocialRelationshipCommandResultKind,
    };

    const NOW_MS: i64 = 1_800_000_000_000;
    const GENERATION: u64 = 19;

    struct TestDirectory(PathBuf);

    impl TestDirectory {
        fn new() -> Self {
            let mut suffix = [0_u8; 8];
            rand::rngs::OsRng.fill_bytes(&mut suffix);
            let path = std::env::temp_dir().join(format!(
                "peers-relationship-resolver-{}",
                u64::from_be_bytes(suffix)
            ));
            fs::create_dir_all(&path).unwrap();
            Self(path)
        }
    }

    impl Drop for TestDirectory {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    #[derive(Clone)]
    struct TestTransport {
        lookup: Vec<u8>,
    }

    impl RelationshipResolverTransport for TestTransport {
        fn dispatch(
            &self,
            exact_payload_bytes: &[u8],
        ) -> Result<Vec<u8>, RelationshipTransportFailure> {
            SocialRelationshipCommand::decode(exact_payload_bytes)
                .map_err(|_| RelationshipTransportFailure::ResponseDecode)?;
            Ok(Vec::new())
        }

        fn lookup(
            &self,
            _command_id: &str,
            _payload_sha256: &[u8],
        ) -> Result<Vec<u8>, RelationshipTransportFailure> {
            Ok(self.lookup.clone())
        }
    }

    #[test]
    fn terminal_relationship_result_is_checkpointed_and_removed() {
        let directory = TestDirectory::new();
        let ledger = activated_ledger(&directory.0);
        let prepared = prepared_relationship("relationship-command-1");
        let command_id = prepared.command_id.clone();
        let payload_sha256 = prepared.payload_sha256.clone();
        RelationshipResolver::admit(
            &ledger,
            &ExactScope::new("station-a", "ptid:alice").unwrap(),
            GENERATION,
            prepared,
        )
        .unwrap();
        let lookup = relationship_lookup_bytes(
            &command_id,
            &payload_sha256,
            SocialRelationshipCommandResultKind::Committed,
        );

        let resolved = RelationshipResolver::resolve_next(
            &ledger,
            &TestTransport { lookup },
            GENERATION,
            NOW_MS + 1,
            7,
        )
        .unwrap()
        .unwrap();

        assert_eq!(resolved.state, MobileDurableCommandState::Committed);
        assert!(resolved.projection_checkpoint.is_some());
        assert!(ledger.get(&command_id).unwrap().is_none());
        let checkpoints = ledger.list_projection_checkpoints().unwrap();
        assert_eq!(checkpoints.len(), 1);
        assert!(checkpoints[0].social_relationship_lookup.is_some());
    }

    #[test]
    fn relationship_resolver_selects_the_relationship_payload_lane() {
        let directory = TestDirectory::new();
        let ledger = activated_ledger(&directory.0);
        RelationshipResolver::admit(
            &ledger,
            &ExactScope::new("station-a", "ptid:alice").unwrap(),
            GENERATION,
            prepared_relationship("relationship-command-2"),
        )
        .unwrap();
        assert!(RelationshipResolver::resolve_next(
            &ledger,
            &TestTransport {
                lookup: relationship_lookup_bytes(
                    "relationship-command-2",
                    &ledger
                        .get("relationship-command-2")
                        .unwrap()
                        .unwrap()
                        .payload_sha256,
                    SocialRelationshipCommandResultKind::Committed,
                ),
            },
            GENERATION,
            NOW_MS + 1,
            9,
        )
        .unwrap()
        .is_some());
    }

    fn activated_ledger(directory: &Path) -> CommandLedger {
        let ledger = CommandLedger::new();
        ledger
            .activate(LedgerActivation {
                paths: LedgerPaths {
                    database_path: directory.join("command-ledger-v2.db"),
                    legacy_v1: None,
                },
                scope: CommandScope::new("station-a", "ptid:alice").unwrap(),
                trusted_command_key: TrustedCommandKey::new(
                    [7; 32],
                    ScopeKeyMetadata {
                        kek_id: "install-kek-1".to_string(),
                        install_epoch: vec![3; 32],
                        command_key_id: "command-key-1".to_string(),
                    },
                )
                .unwrap(),
                runtime_generation: GENERATION,
                now_ms: NOW_MS,
            })
            .unwrap();
        ledger
    }

    fn prepared_relationship(command_id: &str) -> PreparedRelationshipAdmission {
        let actor = ActorRef {
            ptid: "ptid:alice".to_string(),
            acct: String::new(),
            kind: ActorKind::Person as i32,
        };
        let command = SocialRelationshipCommand {
            body: Some(SocialRelationshipCommandBody {
                format_version: 1,
                command_id: command_id.to_string(),
                action: SocialRelationshipAction::Block as i32,
                actor: Some(actor.clone()),
                target_actor: Some(ActorRef {
                    ptid: "ptid:bob".to_string(),
                    acct: String::new(),
                    kind: ActorKind::Person as i32,
                }),
                actor_home_station_peer_id: "station-a".to_string(),
                target_home_station_peer_id: "station-b".to_string(),
                observed_revision: 0,
                created_at: Some(crate::runtime::command_ledger::entry::millis_to_timestamp(
                    NOW_MS,
                )),
                expires_at: Some(crate::runtime::command_ledger::entry::millis_to_timestamp(
                    NOW_MS + 600_000,
                )),
                authorizing_device: Some(ActorDeviceRef {
                    actor: Some(actor),
                    device_id: "device-a".to_string(),
                }),
            }),
            signing_key_id: "signing-key-a".to_string(),
            actor_device_signature: vec![7; 64],
        };
        let exact_payload_bytes = command.encode_to_vec();
        PreparedRelationshipAdmission {
            command_id: command_id.to_string(),
            ordering_key: "social-relationship:ptid:alice:ptid:bob".to_string(),
            payload_sha256: Sha256::digest(&exact_payload_bytes).to_vec(),
            exact_payload_bytes,
        }
    }

    fn relationship_lookup_bytes(
        command_id: &str,
        payload_sha256: &[u8],
        result_kind: SocialRelationshipCommandResultKind,
    ) -> Vec<u8> {
        LookupSocialRelationshipCommandResultResponse {
            state: SocialRelationshipCommandLookupState::TerminalResult as i32,
            command_id: command_id.to_string(),
            command_payload_sha256: payload_sha256.to_vec(),
            terminal_result: Some(SocialRelationshipCommandResult {
                command_id: command_id.to_string(),
                command_payload_sha256: payload_sha256.to_vec(),
                kind: result_kind as i32,
                event: None,
                projection: Some(Default::default()),
                error_code: 0,
                retryable: false,
            }),
        }
        .encode_to_vec()
    }
}
