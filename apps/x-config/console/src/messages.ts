import en from "../../../../packages/locales/en/common.json";
import zhCN from "../../../../packages/locales/zh-CN/common.json";

const locale = typeof navigator === "undefined" ? "en" : navigator.language;
const dictionary = (locale.toLowerCase().startsWith("zh") ? zhCN : en) as Record<
  string,
  string
>;

function message(name: string): string {
  const key = `xConfig.${name}`;
  return dictionary[key] ?? (zhCN as Record<string, string>)[key] ?? key;
}

function counted(name: string, count: number): string {
  return message(name).replace("{{count}}", String(count));
}

