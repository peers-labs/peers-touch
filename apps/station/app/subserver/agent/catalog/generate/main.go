package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
)

const (
	assetRelativePath  = "packages/agent-catalog/official-catalog.v1.envelope.json"
	outputRelativePath = "apps/station/app/subserver/agent/catalog/official_catalog_gen.go"
	maxEnvelopeBytes   = 2 * 1024 * 1024
)

type envelopeHeader struct {
	SchemaVersion   string `json:"schemaVersion"`
	PayloadBase64   string `json:"payloadBase64"`
	SigningKeyID    string `json:"signingKeyId"`
	SignatureBase64 string `json:"signatureBase64"`
}

func main() {
	check := flag.Bool("check", false, "verify the generated projection without writing")
	flag.Parse()

	root, err := findRepositoryRoot()
	if err != nil {
		fail(err)
	}
	assetPath := filepath.Join(root, assetRelativePath)
	outputPath := filepath.Join(root, outputRelativePath)
	envelope, err := os.ReadFile(assetPath)
	if err != nil {
		fail(fmt.Errorf("read canonical catalog: %w", err))
	}
	if len(envelope) == 0 || len(envelope) > maxEnvelopeBytes {
		fail(fmt.Errorf("canonical catalog size %d is outside 1..%d", len(envelope), maxEnvelopeBytes))
	}
	var header envelopeHeader
	if err := json.Unmarshal(envelope, &header); err != nil {
		fail(fmt.Errorf("decode canonical catalog: %w", err))
	}
	if header.SchemaVersion != "peers.package-catalog.envelope.v1" ||
		header.PayloadBase64 == "" ||
		header.SigningKeyID == "" ||
		header.SignatureBase64 == "" {
		fail(fmt.Errorf("canonical catalog envelope header is incomplete"))
	}

	digest := sha256.Sum256(envelope)
	source, err := format.Source([]byte(fmt.Sprintf(`// Code generated by go generate ./subserver/agent/catalog; DO NOT EDIT.

package catalog

const (
	OfficialPackageCatalogMediaType = "application/json"
	OfficialPackageCatalogDistributionID = "peers-official-station-v1"
	OfficialPackageCatalogEnvelopeSHA256 = %s
	officialPackageCatalogEnvelopeJSON = %s
)

func OfficialPackageCatalogEnvelope() []byte {
	return []byte(officialPackageCatalogEnvelopeJSON)
}
`, strconv.Quote(hex.EncodeToString(digest[:])), strconv.Quote(string(envelope)))))
	if err != nil {
		fail(fmt.Errorf("format generated projection: %w", err))
	}

	if *check {
		current, err := os.ReadFile(outputPath)
		if err != nil {
			fail(fmt.Errorf("read generated projection: %w", err))
		}
		if !bytes.Equal(current, source) {
			fail(fmt.Errorf("generated projection is stale; run go generate ./subserver/agent/catalog"))
		}
		return
	}
	if err := writeAtomic(outputPath, source); err != nil {
		fail(err)
	}
}

func findRepositoryRoot() (string, error) {
	current, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(current, assetRelativePath)); err == nil {
			return current, nil
		}
		parent := filepath.Dir(current)
		if parent == current {
			return "", fmt.Errorf("repository root containing %s was not found", assetRelativePath)
		}
		current = parent
	}
}

func writeAtomic(path string, content []byte) error {
	temp, err := os.CreateTemp(filepath.Dir(path), ".official_catalog_gen-*.go")
	if err != nil {
		return fmt.Errorf("create generated projection: %w", err)
	}
	tempPath := temp.Name()
	defer os.Remove(tempPath)
	if _, err := temp.Write(content); err != nil {
		_ = temp.Close()
		return fmt.Errorf("write generated projection: %w", err)
	}
	if err := temp.Close(); err != nil {
		return fmt.Errorf("close generated projection: %w", err)
	}
	if err := os.Rename(tempPath, path); err != nil {
		return fmt.Errorf("replace generated projection: %w", err)
	}
	return nil
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
