use std::path::{Path, PathBuf};
use std::process::Command;

const AGENT_V2_PROTO_FILES: &[&str] = &[
    "domain/agent/agent.proto",
    "domain/agent/agent_config.proto",
    "domain/agent/turn_stream.proto",
    "domain/agent/home.proto",
    "domain/agent/capability.proto",
    "domain/agent/evaluation.proto",
    "domain/agent/package_catalog.proto",
];

fn main() {
    emit_source_commit();
    tauri_build::build();
    compile_protos();
}

fn emit_source_commit() {
    println!("cargo:rerun-if-env-changed=PT_BUILD_SOURCE_COMMIT");
    let repo_root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../..");
    let mut git_inputs = vec!["HEAD".to_string()];
    if let Some(symbolic_ref) = git_stdout(&repo_root, &["symbolic-ref", "--quiet", "HEAD"]) {
        git_inputs.push(symbolic_ref);
    }
    git_inputs.push("packed-refs".to_string());

    for git_input in git_inputs {
        if let Some(path) = git_stdout(&repo_root, &["rev-parse", "--git-path", &git_input]) {
            let path = PathBuf::from(path);
            let path = if path.is_absolute() {
                path
            } else {
                repo_root.join(path)
            };
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }
    let commit = std::env::var("PT_BUILD_SOURCE_COMMIT")
        .ok()
        .or_else(|| git_stdout(&repo_root, &["rev-parse", "HEAD"]))
        .unwrap_or_else(|| "0000000000000000000000000000000000000000".to_string());
    assert!(
        commit.len() == 40 && commit.bytes().all(|byte| byte.is_ascii_hexdigit()),
        "Desktop build source commit is invalid"
    );
    println!("cargo:rustc-env=PT_BUILD_SOURCE_COMMIT={commit}");
}

fn git_stdout(repo_root: &Path, args: &[&str]) -> Option<String> {
    Command::new("git")
        .args(args)
        .current_dir(repo_root)
        .output()
        .ok()
        .filter(|output| output.status.success())
        .and_then(|output| String::from_utf8(output.stdout).ok())
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty())
}

/// Compile proto definitions used by the Desktop BFF layer.
/// Chat and common protos are generated by messaging-core (single owner).
/// Only non-chat packages consumed by Tauri commands / gateway are compiled here.
fn compile_protos() {
    let proto_root = PathBuf::from("../../../model");
    if !proto_root.join("domain").exists() {
        return;
    }

    for proto_file in AGENT_V2_PROTO_FILES {
        let path = proto_root.join(proto_file);
        assert!(
            path.is_file(),
            "Required Modern Chat Agent V2 proto is missing: {}",
            path.display()
        );
    }

    let proto_files: Vec<PathBuf> = [
        "domain/notification/notification.proto",
        "domain/actor/actor.proto",
        "domain/actor/actor_signup.proto",
        "domain/actor/actor_status.proto",
        "domain/actor/session.proto",
        "domain/actor/session_api.proto",
        "domain/actor/preferences.proto",
        "domain/auth/auth.proto",
        "domain/access_gate/access_gate.proto",
        "domain/core/core.proto",
        "domain/error/error.proto",
        "domain/events/events.proto",
        "domain/peer/peer.proto",
        "domain/peer/station_identity.proto",
        "domain/presence/presence.proto",
        "domain/oss/oss.proto",
        "domain/oauth/broker_bridge.proto",
        "domain/oauth/oauth.proto",
        "domain/oauth/mobile_oauth.proto",
        "domain/manage/health.proto",
        "domain/applet/applet.proto",
        "domain/launcher/launcher.proto",
        "domain/message/conversation.proto",
        "domain/activity/activity.proto",
        "domain/secure_content/content.proto",
        "domain/secure_content/prekey.proto",
        "domain/secure_content/object.proto",
        "domain/ai_chat/chat.proto",
        "domain/ai_chat/provider.proto",
        "domain/ai_chat/ai_models.proto",
        "domain/ai_chat/session_messages.proto",
        "domain/ai_chat/message_messages.proto",
        "domain/ai_chat/access_control.proto",
        "domain/social/post.proto",
        "domain/social/comment.proto",
        "domain/social/media.proto",
        "domain/social/poll.proto",
        "domain/social/relationship.proto",
        "domain/social/circle.proto",
        "domain/social/private_content.proto",
        "domain/agent/skill.proto",
        "domain/agent/memory.proto",
        "domain/realtime/event.proto",
        "domain/federation/federation_self.proto",
        "domain/federation/federation_resolve.proto",
        "domain/federation/federation_health.proto",
        "domain/federation/federation_discovery.proto",
        "domain/federation/federation_projection_service.proto",
        "domain/federation/delivery.proto",
        "domain/federation/profile.proto",
        "domain/recovery/recovery.proto",
    ]
    .iter()
    .chain(AGENT_V2_PROTO_FILES.iter())
    .map(|p| proto_root.join(p))
    .filter(|p| p.exists())
    .collect();

    if proto_files.is_empty() {
        return;
    }

    for pf in &proto_files {
        println!("cargo:rerun-if-changed={}", pf.display());
    }

    prost_build::Config::new()
        .extern_path(".peers_touch.model.chat.v1", "crate::model::chat")
        .extern_path(".peers_touch.model.common.v1", "crate::model::common")
        .compile_protos(&proto_files, &[&proto_root])
        .expect("Failed to compile proto files");
}
