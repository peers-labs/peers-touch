#!/usr/bin/env bash
# deploy-testnet.sh — Deploy a 3-node federated test network
#
# Usage:
#   ./deploy-testnet.sh {relay|station|all|status|down}
#
# Architecture:
#   - 3 nodes (a, b, c) each running 1 Relay + 1 Station + 2 PostgreSQL
#   - 3 Relays form a mesh (each bootstraps to the other 2)
#   - 3 Stations connect to ALL 3 Relays for maximum fault tolerance
#   - Any 2 relays can fail and federation still works
#
# Remote layout:
#   ~/peers-touch/repo/         — git source tree
#   ~/peers-touch/relay.env     — relay compose env file
#   ~/peers-touch/station.env   — station compose env file
#   ~/peers-touch/.relay_*      — persistent secrets for relay
#   ~/peers-touch/.station_*    — persistent secrets for station
#
# Requires: ssh, curl, jq (local); docker, docker compose, openssl (remote)

set -euo pipefail

# ── Node definitions ──────────────────────────────────────────────────────────
# Using parallel arrays for bash 3.2 (macOS) compatibility

NODE_NAMES=(a b c)
NODE_IPS_a="10.37.94.156"
NODE_IPS_b="10.37.195.98"
NODE_IPS_c="10.37.246.80"
SSH_USER="shuxian"

get_ip() { eval echo "\$NODE_IPS_$1"; }

# ── Port allocation (identical on all nodes) ──────────────────────────────────

RELAY_HTTP_PORT=18081
RELAY_LIBP2P_PORT=4002
RELAY_STREAM_PORT=4501
STATION_HTTP_PORT=18080
STATION_LIBP2P_PORT=4001

# ── Remote paths ──────────────────────────────────────────────────────────────

REMOTE_BASE="~/peers-touch"
REMOTE_REPO="~/peers-touch/repo"
COMPOSE_FILE="~/peers-touch/repo/tooling/docker/compose.yml"

# ── Helpers ───────────────────────────────────────────────────────────────────

log_section() { echo ""; echo "══════════════════════════════════════════════════════════"; echo "  $1"; echo "══════════════════════════════════════════════════════════"; }
log_step()    { echo "  --> $1"; }
log_info()    { echo "      $1"; }
log_warn()    { echo "  [!] $1"; }

ssh_cmd() {
  local node="$1"; shift
  local ip
  ip=$(get_ip "$node")
  ssh -o ConnectTimeout=5 -o StrictHostKeyChecking=no "${SSH_USER}@${ip}" "$@"
}

# Node a (.156) requires sg docker wrapper because docker group was recently added
docker_cmd() {
  local node="$1"; shift
  local cmd="$*"
  if [[ "$node" == "a" ]]; then
    ssh_cmd "$node" "sg docker -c '$cmd'"
  else
    ssh_cmd "$node" "$cmd"
  fi
}

# ── Secret management (generate once, persist on remote) ──────────────────────

ensure_secret() {
  local node="$1"
  local secret_file="$2"
  local remote_path="${REMOTE_BASE}/${secret_file}"

  # Read existing or generate new
  local value
  value=$(ssh_cmd "$node" "cat ${remote_path} 2>/dev/null || (mkdir -p ${REMOTE_BASE} && openssl rand -hex 32 | tee ${remote_path})")
  echo "$value"
}

ensure_db_password() {
  local node="$1"
  local secret_file="$2"
  local remote_path="${REMOTE_BASE}/${secret_file}"

  local value
  value=$(ssh_cmd "$node" "cat ${remote_path} 2>/dev/null || (mkdir -p ${REMOTE_BASE} && openssl rand -hex 16 | tee ${remote_path})")
  echo "$value"
}

# ── Ubuntu base image transfer for node a ─────────────────────────────────────
# Node a has no ubuntu:22.04 and Docker Hub is unreachable.
# Transfer from node b if missing.

ensure_ubuntu_image_on_a() {
  log_step "Checking ubuntu:22.04 on node a..."
  local has_image
  has_image=$(docker_cmd "a" "docker images -q ubuntu:22.04" 2>/dev/null || echo "")
  if [[ -z "$has_image" ]]; then
    log_warn "ubuntu:22.04 missing on node a — transferring from node b..."
    ssh "${SSH_USER}@$(get_ip b)" "docker save ubuntu:22.04" | \
      ssh "${SSH_USER}@$(get_ip a)" 'sg docker -c "docker load"'
    log_info "Transfer complete."
  else
    log_info "ubuntu:22.04 already present on node a."
  fi
}

# ── Environment file generation ───────────────────────────────────────────────

generate_relay_env() {
  local node="$1"
  local bootstrap_nodes="${2:-}"
  local ip
  ip=$(get_ip "$node")

  local auth_secret db_password
  auth_secret=$(ensure_secret "$node" ".relay_auth_secret")
  db_password=$(ensure_db_password "$node" ".relay_db_password")

  ssh_cmd "$node" "cat > ${REMOTE_BASE}/relay.env" <<EOF
# Relay environment for node ${node} (${ip})
# Auto-generated by deploy-testnet.sh — $(date -Iseconds)
COMPOSE_PROJECT_NAME=pt-relay-${node}

PEERS_AUTH_SECRET=${auth_secret}
PEERS_DB_PASSWORD=${db_password}

POSTGRES_USER=peers
POSTGRES_DB=peers_relay_${node}

RELAY_STATION_PORT=${RELAY_HTTP_PORT}
LIBP2P_PORT=${RELAY_LIBP2P_PORT}
RELAY_STREAM_PORT=${RELAY_STREAM_PORT}
RELAY_STREAM_LISTEN_ADDR=:${RELAY_STREAM_PORT}

PEERS_LIBP2P_PUBLIC_ADDRS=/ip4/${ip}/tcp/${RELAY_LIBP2P_PORT}
PEERS_NODE_SERVER_BASEURL=http://${ip}:${RELAY_HTTP_PORT}
PEERS_BOOTSTRAP_NODES=${bootstrap_nodes}

PEERS_NODE_LABEL=relay-${node}
EOF
}

generate_station_env() {
  local node="$1"
  local bootstrap_nodes="$2"
  local ip
  ip=$(get_ip "$node")

  local auth_secret db_password
  auth_secret=$(ensure_secret "$node" ".station_auth_secret")
  db_password=$(ensure_db_password "$node" ".station_db_password")

  ssh_cmd "$node" "cat > ${REMOTE_BASE}/station.env" <<EOF
# Station environment for node ${node} (${ip})
# Auto-generated by deploy-testnet.sh — $(date -Iseconds)
COMPOSE_PROJECT_NAME=pt-station-${node}

PEERS_AUTH_SECRET=${auth_secret}
PEERS_DB_PASSWORD=${db_password}

POSTGRES_USER=peers
POSTGRES_DB=peers_station_${node}

STATION_PORT=${STATION_HTTP_PORT}
LIBP2P_PORT=${STATION_LIBP2P_PORT}
STATION_HOST=${ip}

PEERS_LIBP2P_PUBLIC_ADDRS=/ip4/${ip}/tcp/${STATION_LIBP2P_PORT}
PEERS_NODE_SERVER_BASEURL=http://${ip}:${STATION_HTTP_PORT}
PEERS_BOOTSTRAP_NODES=${bootstrap_nodes}

PEERS_FEDERATION_DIRECT_OUTBOUND=true
PEERS_FEDERATION_DIRECT_INBOUND=true

RELAY_CLIENT_ENABLED=true
RELAY_CLIENT_RELAY_URL=http://${ip}:${RELAY_HTTP_PORT}
RELAY_CLIENT_RELAY_STREAM_ADDR=${ip}:${RELAY_STREAM_PORT}
RELAY_CLIENT_LABEL=station-${node}

PEERS_NODE_LABEL=node-${node}
EOF
}

# ── Relay deployment (two-pass for mesh bootstrap) ────────────────────────────

deploy_relays() {
  log_section "Deploying Relays (3-node mesh)"

  # Ensure ubuntu base image on node a before building
  ensure_ubuntu_image_on_a

  # ── Pass 1: Start relays without bootstrap (generate PeerIDs) ──
  log_step "Pass 1: Starting relays without bootstrap nodes..."

  for node in "${NODE_NAMES[@]}"; do
    log_info "Generating relay .env for node ${node} (no bootstrap)..."
    generate_relay_env "$node" ""
  done

  for node in "${NODE_NAMES[@]}"; do
    local ip
    ip=$(get_ip "$node")
    log_info "Starting relay on node ${node} (${ip})..."
    docker_cmd "$node" "docker compose -p pt-relay-${node} -f ${COMPOSE_FILE} --env-file ${REMOTE_BASE}/relay.env --profile relay --profile infra up -d --build"
  done

  # Wait for relays to become healthy and generate their PeerIDs
  log_step "Waiting for relays to initialize (30s)..."
  sleep 30

  # ── Discover PeerIDs ──
  log_step "Discovering relay PeerIDs..."

  for node in "${NODE_NAMES[@]}"; do
    local ip
    ip=$(get_ip "$node")
    local info peer_id

    # Retry up to 5 times with 10s interval
    for attempt in $(seq 1 5); do
      info=$(curl -sf "http://${ip}:${RELAY_HTTP_PORT}/sub-bootstrap/info" 2>/dev/null || echo "")
      if [[ -n "$info" ]]; then
        break
      fi
      if [[ "$attempt" -lt 5 ]]; then
        log_warn "Relay on ${node} not ready yet, retrying in 10s (attempt ${attempt}/5)..."
        sleep 10
      fi
    done

    if [[ -z "$info" ]]; then
      echo "ERROR: Cannot reach relay on node ${node} (${ip}:${RELAY_HTTP_PORT})" >&2
      exit 1
    fi

    peer_id=$(echo "$info" | grep -o '"peer_id":"[^"]*"' | head -1 | cut -d'"' -f4)
    if [[ -z "$peer_id" ]]; then
      echo "ERROR: Could not extract PeerID from relay on node ${node}" >&2
      exit 1
    fi

    eval "RELAY_PEER_ID_${node}=\$peer_id"
    log_info "Node ${node}: PeerID = ${peer_id}"
  done

  # ── Pass 2: Update .env with full mesh bootstrap and restart ──
  log_step "Pass 2: Updating relay .env files with mesh bootstrap nodes..."

  for node in "${NODE_NAMES[@]}"; do
    # Build bootstrap list: multiaddrs of the OTHER 2 relays
    local bootstrap_list=""
    for other in "${NODE_NAMES[@]}"; do
      if [[ "$other" != "$node" ]]; then
        local other_ip
        other_ip=$(get_ip "$other")
        local other_peer_id
        other_peer_id=$(eval echo "\$RELAY_PEER_ID_${other}")
        local multiaddr="/ip4/${other_ip}/tcp/${RELAY_LIBP2P_PORT}/p2p/${other_peer_id}"
        if [[ -n "$bootstrap_list" ]]; then
          bootstrap_list="${bootstrap_list},${multiaddr}"
        else
          bootstrap_list="${multiaddr}"
        fi
      fi
    done

    log_info "Node ${node} bootstrap: ${bootstrap_list}"
    generate_relay_env "$node" "$bootstrap_list"
  done

  # Restart relays with updated bootstrap
  log_step "Restarting relays with mesh bootstrap..."
  for node in "${NODE_NAMES[@]}"; do
    local ip
    ip=$(get_ip "$node")
    log_info "Restarting relay on node ${node} (${ip})..."
    docker_cmd "$node" "docker compose -p pt-relay-${node} -f ${COMPOSE_FILE} --env-file ${REMOTE_BASE}/relay.env --profile relay --profile infra up -d --build"
  done

  log_step "Relay mesh deployment complete."
  echo ""
  for node in "${NODE_NAMES[@]}"; do
    local node_ip
    node_ip=$(get_ip "$node")
    local node_peer_id
    node_peer_id=$(eval echo "\$RELAY_PEER_ID_${node}")
    log_info "Relay ${node}: http://${node_ip}:${RELAY_HTTP_PORT}  PeerID=${node_peer_id}"
  done
}

# ── Station deployment ────────────────────────────────────────────────────────

deploy_stations() {
  log_section "Deploying Stations (3 nodes, all relay bootstrap)"

  # Ensure ubuntu base image on node a before building
  ensure_ubuntu_image_on_a

  # Discover relay PeerIDs (relays must already be running)
  log_step "Discovering relay PeerIDs for station bootstrap..."

  for node in "${NODE_NAMES[@]}"; do
    local ip
    ip=$(get_ip "$node")
    local info peer_id

    info=$(curl -sf "http://${ip}:${RELAY_HTTP_PORT}/sub-bootstrap/info" 2>/dev/null || echo "")
    if [[ -z "$info" ]]; then
      echo "ERROR: Cannot reach relay on node ${node} (${ip}:${RELAY_HTTP_PORT}). Deploy relays first." >&2
      exit 1
    fi

    peer_id=$(echo "$info" | grep -o '"peer_id":"[^"]*"' | head -1 | cut -d'"' -f4)
    if [[ -z "$peer_id" ]]; then
      echo "ERROR: Could not extract PeerID from relay on node ${node}" >&2
      exit 1
    fi

    eval "RELAY_PEER_ID_${node}=\$peer_id"
    log_info "Relay ${node}: PeerID = ${peer_id}"
  done

  # Build full bootstrap list (ALL 3 relays) for stations
  local full_bootstrap=""
  for node in "${NODE_NAMES[@]}"; do
    local ip
    ip=$(get_ip "$node")
    local peer_id
    peer_id=$(eval echo "\$RELAY_PEER_ID_${node}")
    local multiaddr="/ip4/${ip}/tcp/${RELAY_LIBP2P_PORT}/p2p/${peer_id}"
    if [[ -n "$full_bootstrap" ]]; then
      full_bootstrap="${full_bootstrap},${multiaddr}"
    else
      full_bootstrap="${multiaddr}"
    fi
  done

  log_info "Station bootstrap list: ${full_bootstrap}"

  # Generate station .env and deploy
  for node in "${NODE_NAMES[@]}"; do
    local ip
    ip=$(get_ip "$node")
    log_step "Deploying station on node ${node} (${ip})..."
    generate_station_env "$node" "$full_bootstrap"
    docker_cmd "$node" "docker compose -p pt-station-${node} -f ${COMPOSE_FILE} --env-file ${REMOTE_BASE}/station.env --profile station --profile infra up -d --build"
  done

  log_step "Station deployment complete."
  echo ""
  for node in "${NODE_NAMES[@]}"; do
    local node_ip
    node_ip=$(get_ip "$node")
    log_info "Station ${node}: http://${node_ip}:${STATION_HTTP_PORT}"
  done
}

# ── Status check ──────────────────────────────────────────────────────────────

check_status() {
  log_section "Test Network Status"

  local all_ok=true

  for node in "${NODE_NAMES[@]}"; do
    local ip
    ip=$(get_ip "$node")
    echo ""
    log_step "Node ${node} (${ip}):"

    # Check relay
    local relay_health
    relay_health=$(curl -sf --max-time 5 "http://${ip}:${RELAY_HTTP_PORT}/sub-oss/healthz" 2>/dev/null || echo "UNREACHABLE")
    if [[ "$relay_health" == "UNREACHABLE" ]]; then
      log_warn "Relay:   DOWN"
      all_ok=false
    else
      log_info "Relay:   UP (port ${RELAY_HTTP_PORT})"
    fi

    # Check station
    local station_health
    station_health=$(curl -sf --max-time 5 "http://${ip}:${STATION_HTTP_PORT}/sub-oss/healthz" 2>/dev/null || echo "UNREACHABLE")
    if [[ "$station_health" == "UNREACHABLE" ]]; then
      log_warn "Station: DOWN"
      all_ok=false
    else
      log_info "Station: UP (port ${STATION_HTTP_PORT})"
    fi
  done

  echo ""
  if [[ "$all_ok" == "true" ]]; then
    log_step "All 6 services healthy."
  else
    log_warn "Some services are down. Check logs on the affected nodes."
    exit 1
  fi
}

# ── Tear down ─────────────────────────────────────────────────────────────────

tear_down() {
  log_section "Tearing down test network"

  for node in "${NODE_NAMES[@]}"; do
    local ip
    ip=$(get_ip "$node")
    log_step "Stopping services on node ${node} (${ip})..."

    # Stop station
    docker_cmd "$node" "docker compose -p pt-station-${node} -f ${COMPOSE_FILE} --env-file ${REMOTE_BASE}/station.env --profile station --profile infra down" 2>/dev/null || true

    # Stop relay
    docker_cmd "$node" "docker compose -p pt-relay-${node} -f ${COMPOSE_FILE} --env-file ${REMOTE_BASE}/relay.env --profile relay --profile infra down" 2>/dev/null || true
  done

  log_step "All services stopped."
}

# ── Main ──────────────────────────────────────────────────────────────────────

usage() {
  echo "Usage: $0 {relay|station|all|status|down}"
  echo ""
  echo "  relay    Deploy relays on all 3 nodes (two-pass mesh bootstrap)"
  echo "  station  Deploy stations on all 3 nodes (requires relays running)"
  echo "  all      Deploy relays then stations"
  echo "  status   Health-check all 6 services"
  echo "  down     Tear down all services on all nodes"
  exit 1
}

COMMAND="${1:-}"

case "$COMMAND" in
  relay)
    deploy_relays
    ;;
  station)
    deploy_stations
    ;;
  all)
    deploy_relays
    echo ""
    log_step "Waiting for relay mesh to stabilize (15s)..."
    sleep 15
    deploy_stations
    ;;
  status)
    check_status
    ;;
  down)
    tear_down
    ;;
  *)
    usage
    ;;
esac
