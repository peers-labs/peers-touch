#!/usr/bin/env bash
# push-deploy.sh — Push local source to a remote node and rebuild
#
# Usage (from repo root or tooling/docker/):
#   ./tooling/docker/push-deploy.sh [branch] [host]
#   ./tooling/docker/push-deploy.sh main shuxian@10.37.195.98
#   ./tooling/docker/push-deploy.sh feat/applet-sdk shuxian@10.37.195.98
#
# Architecture:
#   - Sends station source via tar+ssh (no GitHub access required)
#   - Runs docker compose build+up on the remote
#   - Port allocation identical to deploy-branch.sh
#   - Designed for internal network test environments
#
# Requires: ssh, tar, curl (local); docker, docker compose (remote)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

BRANCH="${1:-main}"
REMOTE_HOST="${2:-shuxian@10.37.195.98}"
DEPLOY_ROOT="${PEERS_DEPLOY_ROOT:-peers-touch}"

# Sanitize branch name for filesystem/docker usage
SAFE_BRANCH=$(echo "$BRANCH" | sed 's/[^a-zA-Z0-9_-]/_/g' | tr '[:upper:]' '[:lower:]')

# ── Port allocation ───────────────────────────────────────────────────────────
allocate_station_port() {
  if [ "$SAFE_BRANCH" = "main" ] || [ "$SAFE_BRANCH" = "master" ]; then
    echo 18080
  else
    local hash
    hash=$(echo -n "$SAFE_BRANCH" | cksum | awk '{print $1}')
    echo $(( 18082 + (hash % 118) ))
  fi
}

allocate_libp2p_port() {
  if [ "$SAFE_BRANCH" = "main" ] || [ "$SAFE_BRANCH" = "master" ]; then
    echo 4001
  else
    local hash
    hash=$(echo -n "$SAFE_BRANCH" | cksum | awk '{print $1}')
    echo $(( 4003 + (hash % 97) ))
  fi
}

STATION_PORT=$(allocate_station_port)
LIBP2P_PORT=$(allocate_libp2p_port)

echo "═══════════════════════════════════════════════════"
echo "  Branch:        ${BRANCH}"
echo "  Safe name:     ${SAFE_BRANCH}"
echo "  Remote:        ${REMOTE_HOST}"
echo "  Station port:  ${STATION_PORT}"
echo "  libp2p port:   ${LIBP2P_PORT}"
echo "═══════════════════════════════════════════════════"
echo ""

# ── Push source to remote ─────────────────────────────────────────────────────
REMOTE_WORK="~/${DEPLOY_ROOT}/branches/${SAFE_BRANCH}"
REMOTE_REPO="${REMOTE_WORK}/repo"

echo "==> Creating remote directory..."
ssh "$REMOTE_HOST" "mkdir -p ${REMOTE_REPO}"

echo "==> Pushing source (apps/station + tooling/docker)..."
cd "$REPO_ROOT"
tar czf - apps/station tooling/docker .dockerignore 2>/dev/null \
  | ssh "$REMOTE_HOST" "cd ${REMOTE_REPO} && tar xzf -"

echo "==> Source pushed."
echo ""

# ── Discover Relay bootstrap info ─────────────────────────────────────────────
RELAY_BOOTSTRAP_MULTIADDR=""
RELAY_INFO=$(ssh "$REMOTE_HOST" "curl -sf http://10.37.118.48:18081/sub-bootstrap/info 2>/dev/null || echo ''")
if [ -n "$RELAY_INFO" ]; then
  RELAY_PEER_ID=$(echo "$RELAY_INFO" | grep -o '"peer_id":"[^"]*"' | cut -d'"' -f4)
  if [ -n "$RELAY_PEER_ID" ]; then
    RELAY_BOOTSTRAP_MULTIADDR="/ip4/10.37.118.48/tcp/4001/p2p/${RELAY_PEER_ID}"
    echo "  Relay PeerID: ${RELAY_PEER_ID}"
    echo "  Bootstrap:    ${RELAY_BOOTSTRAP_MULTIADDR}"
  fi
fi
echo ""

# ── Ensure .env exists on remote ──────────────────────────────────────────────
REMOTE_IP=$(echo "$REMOTE_HOST" | grep -o '[0-9]\+\.[0-9]\+\.[0-9]\+\.[0-9]\+')

ssh "$REMOTE_HOST" bash -s <<REMOTE_ENV
mkdir -p ${REMOTE_WORK}
[ -f ${REMOTE_WORK}/.auth_secret ] || openssl rand -hex 32 > ${REMOTE_WORK}/.auth_secret
[ -f ${REMOTE_WORK}/.db_password ] || openssl rand -hex 16 > ${REMOTE_WORK}/.db_password
AUTH_SECRET=\$(cat ${REMOTE_WORK}/.auth_secret)
DB_PASSWORD=\$(cat ${REMOTE_WORK}/.db_password)

cat > ${REMOTE_WORK}/.env <<EOFENV
# Auto-generated by push-deploy.sh — \$(date -Iseconds)
COMPOSE_PROJECT_NAME=pt-shuxian-${SAFE_BRANCH}

PEERS_AUTH_SECRET=\${AUTH_SECRET}
PEERS_DB_PASSWORD=\${DB_PASSWORD}

POSTGRES_USER=peers
POSTGRES_DB=peers_${SAFE_BRANCH}

STATION_HOST=${REMOTE_IP}
STATION_PORT=${STATION_PORT}
LIBP2P_PORT=${LIBP2P_PORT}

PEERS_BOOTSTRAP_NODES=${RELAY_BOOTSTRAP_MULTIADDR}
PEERS_LIBP2P_PUBLIC_ADDRS=/ip4/${REMOTE_IP}/tcp/${LIBP2P_PORT}
PEERS_FEDERATION_DIRECT_OUTBOUND=true
PEERS_FEDERATION_DIRECT_INBOUND=true

PEERS_NODE_SERVER_BASEURL=http://${REMOTE_IP}:${STATION_PORT}

RELAY_CLIENT_ENABLED=true
RELAY_CLIENT_RELAY_URL=http://10.37.118.48:18081
RELAY_CLIENT_RELAY_STREAM_ADDR=10.37.118.48:4501
RELAY_CLIENT_INVITE_TOKEN=
RELAY_CLIENT_LABEL=shuxian-${SAFE_BRANCH}
EOFENV
REMOTE_ENV

echo "==> Building and deploying station (${SAFE_BRANCH})..."
echo ""

# ── Deploy ────────────────────────────────────────────────────────────────────
ssh "$REMOTE_HOST" "cd ${REMOTE_REPO} && \
  docker compose -p pt-shuxian-${SAFE_BRANCH} \
    -f tooling/docker/compose.yml \
    --env-file ${REMOTE_WORK}/.env \
    --profile station --profile infra \
    up -d --build" 2>&1 | tail -15

echo ""
echo "═══════════════════════════════════════════════════"
echo "  DEPLOYED: ${BRANCH}"
echo "  URL:      http://${REMOTE_IP}:${STATION_PORT}"
echo "  Health:   curl http://${REMOTE_IP}:${STATION_PORT}/sub-oss/healthz"
echo "═══════════════════════════════════════════════════"
