#!/usr/bin/env bash
# deploy-branch.sh — Branch-aware deployment for Orange Pi
#
# Usage:
#   ./deploy-branch.sh <branch> [repo_url]
#   ./deploy-branch.sh main
#   ./deploy-branch.sh feat/applet-sdk
#
# Architecture:
#   - Relay is always-on (main branch, separate compose project)
#   - Each branch gets its own Station + PostgreSQL compose project
#   - Port allocation: main=18080, others hashed into 18082-18199
#   - All stations relay-client mount onto the shared Relay
#
# Requires: docker, docker compose, git, curl

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
DEPLOY_ROOT="${PEERS_DEPLOY_ROOT:-$HOME/peers-touch}"
REPO_URL="${2:-git@github.com:nicepeerslabs/peers-touch.git}"
BRANCH="${1:?Usage: deploy-branch.sh <branch> [repo_url]}"

# Sanitize branch name for filesystem/docker usage
SAFE_BRANCH=$(echo "$BRANCH" | sed 's/[^a-zA-Z0-9_-]/_/g' | tr '[:upper:]' '[:lower:]')

# ── Port allocation ───────────────────────────────────────────────────────────
allocate_station_port() {
  if [ "$SAFE_BRANCH" = "main" ] || [ "$SAFE_BRANCH" = "master" ]; then
    echo 18080
  else
    local hash
    hash=$(echo -n "$SAFE_BRANCH" | cksum | awk '{print $1}')
    echo $(( 18082 + (hash % 118) ))
  fi
}

allocate_libp2p_port() {
  if [ "$SAFE_BRANCH" = "main" ] || [ "$SAFE_BRANCH" = "master" ]; then
    echo 4002
  else
    local hash
    hash=$(echo -n "$SAFE_BRANCH" | cksum | awk '{print $1}')
    echo $(( 4003 + (hash % 97) ))
  fi
}

STATION_PORT=$(allocate_station_port)
LIBP2P_PORT=$(allocate_libp2p_port)

echo "═══════════════════════════════════════════════════"
echo "  Branch:        ${BRANCH}"
echo "  Safe name:     ${SAFE_BRANCH}"
echo "  Station port:  ${STATION_PORT}"
echo "  libp2p port:   ${LIBP2P_PORT}"
echo "═══════════════════════════════════════════════════"
echo ""

# ── Ensure Relay is running ───────────────────────────────────────────────────
ensure_relay() {
  local relay_status
  relay_status=$(docker compose -p pt-orangepi-relay \
    -f "$SCRIPT_DIR/compose.yml" \
    --profile relay --profile infra \
    ps --status running -q 2>/dev/null | wc -l)

  if [ "$relay_status" -lt 1 ]; then
    echo "==> Relay not running. Starting Relay (main branch)..."
    docker compose -p pt-orangepi-relay \
      -f "$SCRIPT_DIR/compose.yml" \
      --env-file "$SCRIPT_DIR/.env.orangepi-relay" \
      --profile relay --profile infra \
      up -d --build
    echo "==> Waiting for Relay health..."
    sleep 10
  fi
}

# ── Discover Relay bootstrap info ─────────────────────────────────────────────
discover_relay_bootstrap() {
  local info
  info=$(curl -sf "http://127.0.0.1:18081/sub-bootstrap/info" 2>/dev/null || echo "")
  if [ -z "$info" ]; then
    echo "WARNING: Cannot reach Relay at :18081. Bootstrap discovery skipped."
    echo ""
    return
  fi
  RELAY_PEER_ID=$(echo "$info" | grep -o '"peer_id":"[^"]*"' | cut -d'"' -f4)
  if [ -n "$RELAY_PEER_ID" ]; then
    RELAY_BOOTSTRAP_MULTIADDR="/ip4/10.0.0.20/tcp/4001/p2p/${RELAY_PEER_ID}"
    echo "  Relay PeerID: ${RELAY_PEER_ID}"
    echo "  Bootstrap:    ${RELAY_BOOTSTRAP_MULTIADDR}"
  fi
}

# ── Clone/update source ───────────────────────────────────────────────────────
WORK_DIR="${DEPLOY_ROOT}/branches/${SAFE_BRANCH}"
mkdir -p "$WORK_DIR"

if [ -d "$WORK_DIR/repo/.git" ]; then
  echo "==> Updating source (${BRANCH})..."
  cd "$WORK_DIR/repo"
  git fetch origin
  git checkout "$BRANCH" 2>/dev/null || git checkout -b "$BRANCH" "origin/$BRANCH"
  git reset --hard "origin/$BRANCH"
else
  echo "==> Cloning (${BRANCH})..."
  git clone --branch "$BRANCH" --depth 1 "$REPO_URL" "$WORK_DIR/repo"
  cd "$WORK_DIR/repo"
fi

echo ""

# ── Generate .env for this branch ─────────────────────────────────────────────
ensure_relay
RELAY_BOOTSTRAP_MULTIADDR="${RELAY_BOOTSTRAP_MULTIADDR:-}"
discover_relay_bootstrap

ENV_FILE="$WORK_DIR/.env"
cat > "$ENV_FILE" <<EOF
# Auto-generated by deploy-branch.sh — $(date -Iseconds)
COMPOSE_PROJECT_NAME=pt-orangepi-${SAFE_BRANCH}

PEERS_AUTH_SECRET=$(cat "$WORK_DIR/.auth_secret" 2>/dev/null || openssl rand -hex 32 | tee "$WORK_DIR/.auth_secret")
PEERS_DB_PASSWORD=$(cat "$WORK_DIR/.db_password" 2>/dev/null || openssl rand -hex 16 | tee "$WORK_DIR/.db_password")

POSTGRES_USER=peers
POSTGRES_DB=peers_${SAFE_BRANCH}

STATION_HOST=10.0.0.20
STATION_PORT=${STATION_PORT}
LIBP2P_PORT=${LIBP2P_PORT}

PEERS_BOOTSTRAP_NODES=${RELAY_BOOTSTRAP_MULTIADDR}
PEERS_LIBP2P_PUBLIC_ADDRS=/ip4/10.0.0.20/tcp/${LIBP2P_PORT}
PEERS_FEDERATION_DIRECT_OUTBOUND=true
PEERS_FEDERATION_DIRECT_INBOUND=true

PEERS_NODE_SERVER_BASEURL=http://10.0.0.20:${STATION_PORT}

RELAY_CLIENT_ENABLED=true
RELAY_CLIENT_RELAY_URL=http://10.0.0.20:18081
RELAY_CLIENT_RELAY_STREAM_ADDR=10.0.0.20:4501
RELAY_CLIENT_INVITE_TOKEN=
RELAY_CLIENT_LABEL=orangepi-${SAFE_BRANCH}
EOF

echo ""
echo "==> Building and deploying station (${SAFE_BRANCH})..."

# ── Deploy ────────────────────────────────────────────────────────────────────
docker compose -p "pt-orangepi-${SAFE_BRANCH}" \
  -f "$WORK_DIR/repo/tooling/docker/compose.yml" \
  --env-file "$ENV_FILE" \
  --profile station --profile infra \
  up -d --build

echo ""
echo "═══════════════════════════════════════════════════"
echo "  DEPLOYED: ${BRANCH}"
echo "  URL:      http://10.0.0.20:${STATION_PORT}"
echo "  Logs:     docker compose -p pt-orangepi-${SAFE_BRANCH} logs -f station"
echo "  Health:   curl http://10.0.0.20:${STATION_PORT}/sub-oss/healthz"
echo "═══════════════════════════════════════════════════"
