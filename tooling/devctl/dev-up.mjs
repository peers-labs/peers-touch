import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { runBootstrap, BootError } from './bootstrap.mjs';
import { runDoctor } from './doctor.mjs';
import {
  activateProfile,
  initializeProfile,
  localDevPaths,
} from './profile.mjs';
import { startStation, stationStatus } from './station.mjs';
import { ensureRegistryImages } from './images.mjs';

const DEFAULT_PROFILE = 'local';
const DEFAULT_DB_PASSWORD = 'peers_local_dev';

export class DevUpError extends Error {
  constructor(message, detail) {
    super(message);
    this.name = 'DevUpError';
    this.detail = detail;
  }
}

function log(message) {
  process.stdout.write(`[dev-up] ${message}\n`);
}

function shell(command, args, options = {}) {
  const result = spawnSync(command, args, {
    encoding: 'utf8',
    stdio: options.capture ? ['ignore', 'pipe', 'pipe'] : 'inherit',
    env: options.env ?? process.env,
    cwd: options.cwd,
  });
  if (options.capture) {
    return { status: result.status, stdout: result.stdout ?? '', stderr: result.stderr ?? '' };
  }
  if (result.error || result.status !== 0) {
    throw new DevUpError(`command failed: ${command} ${args.join(' ')}`);
  }
  return result;
}

function parseEnvFile(filePath) {
  const values = {};
  if (!fs.existsSync(filePath)) return values;
  for (const line of fs.readFileSync(filePath, 'utf8').split(/\r?\n/u)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/u);
    if (match) values[match[1]] = match[2];
  }
  return values;
}

// Merge managed keys into tooling/docker/.env without touching operator edits.
function ensureComposeEnv(root, options) {
  const dockerDir = path.join(root, 'tooling', 'docker');
  const envFile = path.join(dockerDir, '.env');
  const values = parseEnvFile(envFile);
  const assignments = [];

  if (!values.PEERS_AUTH_SECRET) {
    assignments.push(['PEERS_AUTH_SECRET', crypto.randomBytes(32).toString('hex')]);
  }
  if (!values.PEERS_DB_PASSWORD) {
    assignments.push(['PEERS_DB_PASSWORD', DEFAULT_DB_PASSWORD]);
  }
  if (options.imageRegistry) {
    const registry = options.imageRegistry.replace(/\/$/u, '');
    const registryOverrides = [
      ['PEERS_POSTGRES_IMAGE', `${registry}/pgvector/pgvector:pg16`],
      ['PEERS_STATION_BUILDER_IMAGE', `${registry}/library/golang:1.24`],
      ['PEERS_STATION_BASE_IMAGE', `${registry}/library/ubuntu:22.04`],
    ];
    for (const [key, value] of registryOverrides) {
      if (!values[key]) assignments.push([key, value]);
    }
  }

  if (assignments.length === 0) {
    log('compose .env already complete');
    return { envFile, changed: false };
  }

  const existing = fs.existsSync(envFile) ? fs.readFileSync(envFile, 'utf8').trimEnd() : '';
  const managed = assignments.map(([key, value]) => `${key}=${value}`).join('\n');
  const body = [
    '# Generated by devctl dev-up — gitignored, safe to delete (regenerated).',
    existing,
    managed,
  ].filter(Boolean).join('\n');
  fs.writeFileSync(envFile, `${body}\n`, { mode: 0o600 });
  log(`wrote ${path.relative(root, envFile)} (${assignments.map(([key]) => key).join(', ')})`);
  return { envFile, changed: true };
}

function ensureProfile(root, environment, options) {
  const name = options.profile ?? DEFAULT_PROFILE;
  const slot = Number(options.slot ?? 0);
  const paths = localDevPaths(root);
  const profileFile = path.join(paths.profiles, `${name}.env`);
  if (!fs.existsSync(profileFile)) {
    if (options.profile) {
      throw new DevUpError(
        `profile ${name} does not exist`,
        `Create it first: make profile-init ${name} SLOT=${slot}`,
      );
    }
    log(`creating worktree-local profile ${name} (slot ${slot})`);
    initializeProfile(root, name, slot);
  }
  log(`activating profile ${name}`);
  activateProfile(root, name, environment);
  return name;
}

function gitOwnerEmail(root) {
  const result = shell('git', ['config', 'user.email'], { capture: true, cwd: root });
  return result.status === 0 ? result.stdout.trim() : '';
}

export async function runDevUp(root, environment = process.env, options = {}) {
  const report = {
    profile: null,
    bootstrap: null,
    reloginRequired: false,
    station: null,
    steps: [],
  };

  const doctorReport = runDoctor(root, environment, { toolchainOnly: true });
  report.doctor = {
    summary: doctorReport.summary,
    failed: doctorReport.checks.filter((check) => check.status === 'fail'),
  };

  if (options.checkOnly) {
    return { ...report, checkOnly: true };
  }

  if (report.doctor.failed.length > 0 && options.noInstall) {
    throw new DevUpError(
      'toolchain checks failed and NO_INSTALL is set',
      report.doctor.failed.map((check) => `${check.id}: ${check.remediation ?? 'missing'}`),
    );
  }

  if (!options.noInstall) {
    const bootstrapReport = await runBootstrap(root, environment, {
      withClientDeps: options.withClientDeps === true,
      insecureRegistries: options.insecureRegistries ?? [],
    });
    report.bootstrap = bootstrapReport;
    report.steps.push(...bootstrapReport.actions);
    if (bootstrapReport.reloginRequired) {
      report.reloginRequired = true;
      return report;
    }
  }

  if (!gitOwnerEmail(root)) {
    throw new DevUpError(
      'git user.email is not configured',
      'Set it for this clone: git config user.email "you@example.com" (and user.name), then rerun make dev-up',
    );
  }

  report.profile = ensureProfile(root, environment, options);
  ensureComposeEnv(root, options);

  if (options.imageRegistry) {
    log(`pre-warming images from ${options.imageRegistry}`);
    const mirrored = await ensureRegistryImages(options.imageRegistry, { log });
    report.steps.push(...mirrored.map((entry) => `image:${entry.action}`));
  }

  if (options.pnpmInstall) {
    log('installing pnpm workspace dependencies');
    shell('pnpm', ['install'], { cwd: root });
    report.steps.push('pnpm-install');
  }

  log('starting Station (compose)');
  await startStation(root, environment);
  const status = await stationStatus(root, environment);
  if (!status.health.ok) {
    throw new DevUpError('Station did not become healthy', { url: status.health.url });
  }
  report.station = status;
  report.steps.push('station-started');
  log(`Station healthy at ${status.health.url}`);
  return report;
}

